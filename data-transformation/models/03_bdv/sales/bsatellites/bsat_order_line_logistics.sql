
WITH source_data AS (
    SELECT 
        HK_ORDER_LINE,
        _LOAD_TIMESTAMP,
        _RECORD_SOURCE,
        UPPER(TRIM(RETURNFLAG)) AS RETURN_FLAG_CD,
        UPPER(TRIM(LINESTATUS)) AS LINE_STATUS_CD,
        CAST(SHIPDATE AS DATE) AS SHIP_DT,
        CAST(COMMITDATE AS DATE) AS COMMIT_DT,
        CAST(RECEIPTDATE AS DATE) AS RECEIPT_DT,
        TRIM(SHIPINSTRUCT) AS SHIP_INSTRUCTION_TX,
        UPPER(TRIM(SHIPMODE)) AS SHIP_MODE_CD,
        CAST(CASE WHEN SHIPDATE > COMMITDATE THEN 1 ELSE 0 END AS BOOLEAN) AS IS_LATE_SHIPMENT_FL
    FROM {{ ref('sat_order_line_logistics') }}
),

stage_bdv AS (
    SELECT
        HK_ORDER_LINE,
        _LOAD_TIMESTAMP,
        _RECORD_SOURCE,
        {{ dbt_utils.generate_surrogate_key(['RETURN_FLAG_CD', 'LINE_STATUS_CD', 'SHIP_DT', 'COMMIT_DT', 'RECEIPT_DT', 'SHIP_INSTRUCTION_TX', 'SHIP_MODE_CD', 'IS_LATE_SHIPMENT_FL']) }} AS HD_BDV_ORDER_LINE_LOGISTICS,
        RETURN_FLAG_CD,
        LINE_STATUS_CD,
        SHIP_DT,
        COMMIT_DT,
        RECEIPT_DT,
        SHIP_INSTRUCTION_TX,
        SHIP_MODE_CD,
        IS_LATE_SHIPMENT_FL        
    FROM source_data
)

SELECT * FROM stage_bdv
