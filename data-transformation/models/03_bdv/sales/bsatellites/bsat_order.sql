
WITH source_data AS (
    SELECT 
        HK_ORDER,
        _LOAD_TIMESTAMP,
        _RECORD_SOURCE,
        UPPER(TRIM(ORDERSTATUS)) AS ORDER_STATUS_CD,
        CAST(TOTALPRICE AS NUMBER(38,2)) AS TOTAL_PRICE_VL,
        CAST(ORDERDATE AS DATE) AS ORDER_DT,
        UPPER(TRIM(ORDERPRIORITY)) AS ORDER_PRIORITY_CD,
        TRIM(CLERK) AS CLERK_TX,
        CAST(SHIPPRIORITY AS INTEGER) AS SHIP_PRIORITY_CD,
        TRIM(COMMENT) AS ORDER_COMMENT_TX
    FROM {{ ref('sat_order') }}
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY HK_ORDER
        ORDER BY _LOAD_TIMESTAMP DESC
    ) = 1
),

stage_bdv AS (
    SELECT
        HK_ORDER,
        _LOAD_TIMESTAMP,
        _RECORD_SOURCE,
        {{ dbt_utils.generate_surrogate_key(['ORDER_STATUS_CD', 'TOTAL_PRICE_VL', 'ORDER_DT', 'ORDER_PRIORITY_CD', 'CLERK_TX', 'SHIP_PRIORITY_CD', 'ORDER_COMMENT_TX']) }} AS HD_BDV_ORDER,
        ORDER_STATUS_CD,
        TOTAL_PRICE_VL,
        ORDER_DT,
        ORDER_PRIORITY_CD,
        CLERK_TX,
        SHIP_PRIORITY_CD,
        ORDER_COMMENT_TX        
    FROM source_data
)

SELECT * FROM stage_bdv
